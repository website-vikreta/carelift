import { validate, usDigits, formatUsPhone, toUsPhoneE164Display, spamCheck } from "../src/lib/validation.ts";
import { isRealValue, templateParams } from "../src/lib/emailjs.ts";
let fail = 0;
const t = (name, ok) => { if (!ok) { fail++; console.log("FAIL", name); } };
const good = { name: "Jane O'Neil-Smith", email: "jane@example.com", contact: "(212) 555-0123", zipCode: "10001", duration: "6 weeks", message: "" };
t("good form passes", Object.keys(validate(good)).length === 0);
t("empty name", !!validate({ ...good, name: "" }).name);
t("digits in name", !!validate({ ...good, name: "J4ne" }).name);
t("accent name ok", !validate({ ...good, name: "José Álvarez" }).name);
t("bad email", !!validate({ ...good, email: "jane@" }).email);
t("email no tld", !!validate({ ...good, email: "jane@example" }).email);
t("email space", !!validate({ ...good, email: "ja ne@example.com" }).email);
t("phone 9 digits", !!validate({ ...good, contact: "212555012" }).contact);
t("phone area code 0xx", !!validate({ ...good, contact: "0235550123" }).contact);
t("typed +1 prefix char by char", formatUsPhone("12125550123") === "(212) 555-0123");
t("phone exchange 0xx", !!validate({ ...good, contact: "2120550123" }).contact);
t("phone with +1", !validate({ ...good, contact: "+1 212 555 0123" }).contact);
t("phone with 1 prefix", usDigits("1-212-555-0123") === "2125550123");
t("format", formatUsPhone("2125550123") === "(212) 555-0123");
t("format partial", formatUsPhone("21255") === "(212) 55");
t("e164 display", toUsPhoneE164Display("212-555-0123") === "+1 (212) 555-0123");
t("letters in phone", !!validate({ ...good, contact: "abcdefghij" }).contact);
t("zip 4 digits", !!validate({ ...good, zipCode: "1000" }).zipCode);
t("zip letters", !!validate({ ...good, zipCode: "1000A" }).zipCode);
t("duration unknown option", !!validate({ ...good, duration: "1–3 months" }).duration);
t("duration empty", !!validate({ ...good, duration: "" }).duration);
t("message too long", !!validate({ ...good, message: "x".repeat(1001) }).message);
const tp = templateParams({ ...good, message: "  " });
t("template params match the EmailJS template", JSON.stringify(Object.keys(tp)) === JSON.stringify(["title", "name", "email", "contact", "zipCode", "duration", "message"]));
t("template phone formatted", tp.contact === "+1 (212) 555-0123");
t("template empty message", tp.message === "(no message)");
t("placeholder env value not configured", !isRealValue("your_service_id") && !isRealValue("") && !isRealValue(undefined));
t("real env value configured", isRealValue("service_abc123"));
t("honeypot empty is ok", spamCheck("", 500) === "ok");
t("honeypot filled instantly is dropped", spamCheck("Acme Inc", 800) === "drop");
t("honeypot autofilled by a person is sent, flagged", spamCheck("Acme Inc", 45000) === "flag");
t("flagged subject", templateParams(good, true).title.startsWith("[check: possible spam] "));
t("normal subject", templateParams(good).title.startsWith("Lift chair rental: "));
console.log(fail ? `${fail} failed` : "all validation tests passed");
process.exit(fail ? 1 : 0);
